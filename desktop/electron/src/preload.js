'use strict'

const { contextBridge, ipcRenderer } = require('electron')

function on(channel, callback) {
  const listener = (_event, payload) => callback(payload)
  ipcRenderer.on(channel, listener)
  return () => ipcRenderer.removeListener(channel, listener)
}

contextBridge.exposeInMainWorld('desktop', {
  info: () => ipcRenderer.invoke('app:info'),
  getConfig: () => ipcRenderer.invoke('config:get'),
  saveLines: (lines, defaultLineId) => ipcRenderer.invoke('lines:save', { lines, defaultLineId }),
  resetLines: () => ipcRenderer.invoke('lines:reset'),
  saveSettings: (patch) => ipcRenderer.invoke('settings:save', patch),
  addHistory: (entry) => ipcRenderer.invoke('history:add', entry),
  updateHistory: (entry) => ipcRenderer.invoke('history:update', entry),
  removeHistory: (url) => ipcRenderer.invoke('history:remove', url),
  clearHistory: () => ipcRenderer.invoke('history:clear'),
  playerCommand: (payload) => ipcRenderer.invoke('player:command', payload),
  playerState: () => ipcRenderer.invoke('player:state'),
  pageTitle: (url) => ipcRenderer.invoke('page:title', url),
  resolveSeries: (payload) => ipcRenderer.invoke('series:resolve', payload),
  downloadCurrent: (payload) => ipcRenderer.invoke('download:start', payload),
  cancelDownload: (id) => ipcRenderer.invoke('download:cancel', id),
  downloadSnapshot: (id) => ipcRenderer.invoke('download:snapshot', id),
  openDownloadFolder: () => ipcRenderer.invoke('download:folder'),
  revealDownload: () => ipcRenderer.invoke('download:reveal'),
  onDownloadState: (callback) => on('download:state', callback),
  readClipboard: () => ipcRenderer.invoke('clipboard:read'),
  copyText: (text) => ipcRenderer.invoke('clipboard:write', text),
  parse: (payload) => ipcRenderer.invoke('parse:run', payload),
  shortPlatforms: () => ipcRenderer.invoke('short:platforms'),
  shortResolve: (payload) => ipcRenderer.invoke('short:resolve', payload),
  shortDownload: (payload) => ipcRenderer.invoke('short:download', payload),
  testLines: (payload) => ipcRenderer.invoke('lines:test', payload),
  updateLinesOnline: () => ipcRenderer.invoke('lines:online'),
  openPlatform: (key) => ipcRenderer.invoke('platform:open', key),
  searchPlatform: (key, query) => ipcRenderer.invoke('platform:search', { key, query }),
  openPlatformSite: (key) => ipcRenderer.invoke('platform:open-site', key),
  openExternal: (url) => ipcRenderer.invoke('shell:open-external', url),
  openUserData: () => ipcRenderer.invoke('app:open-userdata'),
  openLogs: () => ipcRenderer.invoke('app:open-logs'),
  createShortcut: () => ipcRenderer.invoke('app:create-shortcut'),
  about: () => ipcRenderer.invoke('app:about'),
  focusMain: () => ipcRenderer.invoke('app:focus-main'),
  setFullscreen: (flag) => ipcRenderer.invoke('app:set-fullscreen', Boolean(flag)),
  getFullscreenState: () => ipcRenderer.invoke('app:fullscreen-state'),
  toggleFullscreen: () => ipcRenderer.invoke('app:toggle-fullscreen'),
  quit: () => ipcRenderer.invoke('app:quit'),
  getUpdateState: () => ipcRenderer.invoke('update:state'),
  checkUpdate: () => ipcRenderer.invoke('update:check'),
  installUpdate: () => ipcRenderer.invoke('update:install'),
  onUpdateState: (callback) => on('update:state', callback),
  onReady: (callback) => on('app:ready', callback),
  onPasteParse: (callback) => on('app:paste-parse', callback),
  onNextLine: (callback) => on('app:next-line', callback),
  onReload: (callback) => on('app:reload', callback),
  onOpenExternal: (callback) => on('app:open-external', callback),
  onExternalParse: (callback) => on('app:external-parse', callback),
  onOpenBrowser: (callback) => on('app:open-browser', callback),
  onCloseBrowser: (callback) => on('app:close-browser', callback),
  onCloseBrowserTab: (callback) => on('app:close-browser-tab', callback),
  onFullscreen: (callback) => on('window:fullscreen', callback),
  onFullscreenToggle: (callback) => on('app:fullscreen-toggle', callback),
})
